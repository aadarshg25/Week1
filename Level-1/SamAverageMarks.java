class SamAverageMarks {

	public static void main(String[] args) {
		String name = "Sam";
		int physicsMark = 95;
		int chemistryMark = 96;
		int MathMark = 94;
		int averageMarks = (physicsMark + chemistryMark + MathMark) / 3;
		System.out.println(name + "'s average mark in PCM is " + averageMarks);

	}
}